#!/usr/bin/env python3
"""Validate the spec and regenerate spec/INDEX.md.

Checks: every requirement line has an ID, a level, an evidence tag and a basis; IDs are unique and consecutive per
prefix; every F<n>/E<n> reference points at a real finding or experiment; every `PREFIX-n` mention resolves; and no text
looks like an internal address or symbol of the original program (the spec must describe behaviour, not code).

usage: python3 spec/check.py          (exit status 1 on any problem)"""
import re, sys, glob, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REQ = re.compile(r'^- \*\*([A-Z]+)-(\d+)\*\* `(MUST|SHOULD|MAY)` `(verified|inferred|untested)`(?: `([^`]*)`)? - (.*)$')
DEC = re.compile(r'^- \*\*(DEC)-(\d+)\*\* - (.*)$')
LEVELS = {'MUST', 'SHOULD', 'MAY'}

findings = {int(m.group(1)) for f in glob.glob(f'{ROOT}/findings/[0-9][0-9]-*.md') if (m := re.match(r'(\d+)-', os.path.basename(f)))}
experiments = {int(m.group(1)) for f in glob.glob(f'{ROOT}/experiments/[0-9][0-9]-*') if (m := re.match(r'(\d+)-', os.path.basename(f)))}

problems, reqs, ids = [], [], set()
files = sorted(glob.glob(f'{HERE}/[0-9][0-9]-*.md'))
texts = {f: open(f).read() for f in files}

for f, text in texts.items():
    name = os.path.basename(f)
    lines = text.split('\n')
    for n, line in enumerate(lines, 1):
        if line.startswith('- **') and re.match(r'- \*\*[A-Z]+-\d+\*\*', line):
            m = REQ.match(line)
            d = DEC.match(line)
            if d:
                ids.add(f'{d.group(1)}-{d.group(2)}'); continue
            if not m:
                problems.append(f'{name}:{n}: malformed requirement line: {line[:70]}'); continue
            prefix, num, level, tag, basis, text_ = m.groups()
            rid = f'{prefix}-{num}'
            if rid in ids: problems.append(f'{name}:{n}: duplicate id {rid}')
            ids.add(rid)
            basis = basis or ''
            for b in basis.split():
                if b in ('DS-Y', 'DS-I'): continue
                mm = re.fullmatch(r'([FE])(\d+)', b)
                if not mm: problems.append(f'{name}:{n}: {rid}: bad basis item {b!r}'); continue
                kind, num_ = mm.group(1), int(mm.group(2))
                if (kind == 'F' and num_ not in findings) or (kind == 'E' and num_ not in experiments):
                    problems.append(f'{name}:{n}: {rid}: {b} does not exist')
            if tag == 'verified' and not basis: problems.append(f'{name}:{n}: {rid}: verified needs a basis')
            reqs.append((rid, prefix, int(num), level, tag, basis, text_, name))

# ids consecutive per prefix
by_prefix = {}
for r in reqs: by_prefix.setdefault(r[1], []).append(r[2])
for p, nums in by_prefix.items():
    if nums != list(range(1, len(nums) + 1)): problems.append(f'{p}: ids are not consecutive 1..{len(nums)}: {nums}')

# every mention of an id must resolve
alltext = '\n'.join(texts.values())
for m in re.finditer(r'`((?:HW|EMU|TRAP|DPMI|LIFE|TEST|DEC)-\d+)`', alltext):
    if m.group(1) not in ids: problems.append(f'reference to unknown id {m.group(1)}')
for m in re.finditer(r'`((?:HW|EMU|TRAP|DPMI|LIFE|TEST)-\d+)` to `((?:HW|EMU|TRAP|DPMI|LIFE|TEST)-\d+)`', alltext):
    for g in m.groups():
        if g not in ids: problems.append(f'reference to unknown id {g}')

# leakage: no internal addresses or symbols of the original program
LEAK = [(r'\bFUN_[0-9A-Fa-f]+', 'decompiler symbol'), (r'\b0x[0-9A-Fa-f]{3,}\b', '0x address'),
        (r'\b[0-9A-Fa-f]{4}:[0-9A-Fa-f]{4,8}\b', 'segment:offset'), (r'\bIP\s*0x', 'IP address'),
        (r'\[[0-9A-Fa-f]{4}\]', 'bracketed data address')]
for f, text in texts.items():
    for n, line in enumerate(text.split('\n'), 1):
        for pat, what in LEAK:
            for m in re.finditer(pat, line):
                problems.append(f'{os.path.basename(f)}:{n}: looks like an internal {what}: {m.group(0)}')

# index
order = ['HW', 'EMU', 'TRAP', 'DPMI', 'LIFE', 'TEST']
reqs.sort(key=lambda r: (order.index(r[1]), r[2]))
counts = {t: sum(1 for r in reqs if r[4] == t) for t in ('verified', 'inferred', 'untested')}
out = ['# Requirement index', '', '*Generated by `python3 spec/check.py`. Do not edit by hand.*', '',
       f'{len(reqs)} requirements: {counts["verified"]} verified, {counts["inferred"]} inferred, {counts["untested"]} untested.', '',
       '| ID | Level | Evidence | Basis | Requirement | File |', '|---|---|---|---|---|---|']
for rid, prefix, num, level, tag, basis, text_, name in reqs:
    short = text_.split('. ')[0].rstrip('.')
    short = (short[:140] + '...') if len(short) > 140 else short
    out.append(f'| {rid} | {level} | {tag} | {basis} | {short.replace("|", "/")} | [{name}]({name}) |')
open(f'{HERE}/INDEX.md', 'w').write('\n'.join(out) + '\n')

if problems:
    print('\n'.join(problems)); print(f'\n{len(problems)} problem(s)'); sys.exit(1)
print(f'OK: {len(reqs)} requirements ({counts["verified"]} verified, {counts["inferred"]} inferred, {counts["untested"]} untested); index written')
